"""Generate writer plans from the engine's imported-set registry.
python tools/rbx_set_doc.py [slug ...]  (Blender exports geometry; Pillow draws the plans.)
"""
import json, math, os, subprocess, sys
from pathlib import Path

E = Path(__file__).resolve().parents[1]
ROOT = E / 'assets' / 'rbxsets'
BLENDER = os.environ.get('BLENDER', 'C:/Program Files/Blender Foundation/Blender 5.2/blender.exe')
MARKER = '<!-- generated by tools/rbx_set_doc.py -->'


def worker(directory):
    sys.path.insert(0, str(E))
    import bpy, assets, rig, sets, space
    bpy.ops.wm.read_factory_settings(use_empty=True); assets.reset(); rig.CAST.clear()
    st = sets.rbx_set(directory.name.split('_', 1)[0])
    pieces = []
    for q in assets.PLACED:
        pieces.append({key: q[key] for key in ('name', 'rect', 'top', 'solid')})
        pieces[-1]['seat'] = '_seat_' in q['name']
        pieces[-1]['faces'] = [[[round((o.matrix_world @ v.co)[i], 4) for i in (0, 1)]
                               for v in [o.data.vertices[k] for k in face.vertices]]
                              for o in q['pivot'].children_recursive if o.type == 'MESH' for face in o.data.polygons]
    bounds = st['bounds']; x0, x1, y0, y1 = bounds
    ch = rig.make('plan probe', (0, 0), 0)
    world = space.World(bpy.context.scene, {'plan probe': ch})
    # Use real meshes: a cluster of skirting can have a room-sized bounding rectangle.
    free = [(x / 2, y / 2) for x in range(math.ceil((x0 + .8) * 2), math.floor((x1 - .8) * 2) + 1)
            for y in range(math.ceil((y0 + .8) * 2), math.floor((y1 - .8) * 2) + 1)
            if world.query(ch, (x / 2, y / 2), 0, frame=0).depth_m == 0]
    remaining = list(free); spots = []
    while remaining and len(spots) < 5:
        if spots:
            p = max(remaining, key=lambda p: min(math.dist(p, s) for s in spots))
        else:
            p = min(remaining, key=lambda p: math.dist(p, ((x0 + x1) / 2, (y0 + y1) / 2)))
        remaining.remove(p)
        if any(math.dist(p, s) < 1.0 for s in spots): continue
        spots.append(p)
    if len(spots) < 3: raise ValueError(f'{directory.name}: only {len(spots)} clear standing spots')
    data = {'slug': directory.name.split('_', 1)[1], 'bounds': bounds, 'pieces': pieces, 'free': free, 'spots': spots}
    cache = E / 'trace' / '_rbx_set_doc'; cache.mkdir(parents=True, exist_ok=True)
    (cache / (directory.name + '.json')).write_text(json.dumps(data), encoding='utf-8')
    print('PLAN_DATA', directory.name, len(pieces), 'pieces', len(spots), 'checked spots')
    return data


def draw(data, path):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 17)
    small = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 14)
    title = ImageFont.truetype('C:/Windows/Fonts/consolab.ttf', 24)
    x0, x1, y0, y1 = data['bounds']; pad = 70; side = 1050
    scale = (side - 2 * pad) / max(x1 - x0, y1 - y0)
    height = max(side + 30, 140 + 25 * len(data['pieces']))
    im = Image.new('RGB', (1900, height), '#ffffff'); dr = ImageDraw.Draw(im)
    def pt(x, y): return pad + (x - x0) * scale, side - pad - (y - y0) * scale
    def rect(a, b, c, d):
        p, q = pt(a, d), pt(b, c)
        return (*p, *q)
    dr.text((pad, 15), data['slug'] + ' / studs', font=title, fill='#172d40')
    dr.rectangle(rect(x0, x1, y0, y1), fill='#eeeeee', outline='#607080')
    for x, y in data['free']:
        dr.rectangle(rect(x - .25, x + .25, y - .25, y + .25), fill='#d8efd9')
    step = 2 if max(x1 - x0, y1 - y0) < 30 else 10
    for x in range(math.ceil(x0 * 2 / step) * step, math.floor(x1 * 2) + 1, step):
        dr.line([pt(x / 2, y0), pt(x / 2, y1)], fill='#c5cbd0')
        dr.text(pt(x / 2, y0 - .35), str(x), font=small, fill='#244762')
    for y in range(math.ceil(y0 * 2 / step) * step, math.floor(y1 * 2) + 1, step):
        dr.line([pt(x0, y / 2), pt(x1, y / 2)], fill='#c5cbd0')
        px, py = pt(x0, y / 2); dr.text((px - 45, py - 7), str(y), font=small, fill='#244762')
    dr.text((1080, 30), 'Piece labels = exact engine names', font=title, fill='#172d40')
    labels = []
    for i, q in enumerate(data['pieces'], 1):
        a, b, c, d = q['rect']; color = '#e8c271' if q['seat'] else '#d5a6a2'
        for face in q['faces']:
            dr.polygon([pt(x, y) for x, y in face], fill=color, outline='#b48c49' if q['seat'] else '#b16a64')
        px, py = pt((a + b) / 2, (c + d) / 2)
        cy = py
        while any(abs(px - x) < 28 and abs(py - y) < 24 for x, y in labels): py -= 24
        if py != cy: dr.line((px, cy, px, py), fill='#382a24', width=2)
        labels.append((px, py))
        dr.rectangle((px - 12, py - 10, px + 12, py + 10), fill='white')
        dr.text((px, py), str(i), font=small, fill='#382a24', anchor='mm')
        dr.text((1080, 75 + 25 * (i - 1)), f"{i:02d} {q['name']}" + (' [seat]' if q['seat'] else ''), font=font, fill='#382a24')
    for i, (x, y) in enumerate(data['spots'], 1):
        px, py = pt(x, y); dr.ellipse((px - 14, py - 14, px + 14, py + 14), fill='#176a52', outline='white', width=2)
        dr.text((px, py), chr(64 + i), font=small, fill='white', anchor='mm')
    dr.text((pad, side - 30), 'Green: sampled standing clearance (yaw 0). Gold: seat. Red: solid footprint.', font=small, fill='#244762')
    dr.text((pad, side - 10), 'A-E: checked standing spots (yaw 0). +X right, +Y up. Grid in studs.', font=small, fill='#244762')
    im.save(path)


def section(directory, data):
    x0, x1, y0, y1 = [v * 2 for v in data['bounds']]
    lines = [f"## {data['slug']}", '', f'Footprint **{x1 - x0:.1f} x {y1 - y0:.1f} studs**; X [{x0:.1f}, {x1:.1f}], Y [{y0:.1f}, {y1:.1f}].',
             f"Plan: [{directory.name}/plan.png]({directory.name}/plan.png). Coordinates assume `at: [0, 0]`, `rot: 0`, `scale: 1`.", '',
             'Clear standing spots (studs; standing R6 at yaw 0, facing -Y; turns/routes need their own clearance checks):', '']
    lines += [f'- {chr(65 + i)}: `[{x * 2:g}, {y * 2:g}]`' for i, (x, y) in enumerate(data['spots'])]
    lines += ['', '| Plan | Exact piece name | Centre [x, y] studs | Size [x, y] studs | Seat |', '|---|---|---|---|---|']
    for i, q in enumerate(data['pieces'], 1):
        a, b, c, d = q['rect']
        lines.append(f"| {i} | `{q['name']}` | [{a + b:.1f}, {c + d:.1f}] | [{(b - a) * 2:.1f}, {(d - c) * 2:.1f}] | {'yes' if q['seat'] else ''} |")
    return '\n'.join(lines)


def main(tags):
    directories = [d for d in sorted(ROOT.iterdir()) if (d / 'scene.json').exists()]
    for d in directories:
        if tags and not any(tag in d.name for tag in tags): continue
        subprocess.run([BLENDER, '-b', '--factory-startup', '--offline-mode', '--python-exit-code', '1', '-P', __file__, '--', str(d)], cwd=E, check=True)
        data = json.loads((E / 'trace' / '_rbx_set_doc' / (d.name + '.json')).read_text(encoding='utf-8'))
        draw(data, d / 'plan.png')
        data.pop('free')
        for piece in data['pieces']: piece.pop('faces')
        (d / 'plan.json').write_text(json.dumps(data, indent=1), encoding='utf-8')
    library = ROOT / 'LIBRARY.md'
    intro = library.read_text(encoding='utf-8').split(MARKER)[0].rstrip()
    sections = [section(d, json.loads((d / 'plan.json').read_text(encoding='utf-8'))) for d in directories if (d / 'plan.json').exists()]
    import re
    for d in directories:
        if not (d / 'plan.json').exists(): continue
        count = len(json.loads((d / 'plan.json').read_text(encoding='utf-8'))['pieces'])
        intro = re.sub(r'(^\| ' + d.name.split('_', 1)[0] + r' \|.*\| )\d+( \|$)',
                       lambda m: m[1] + str(count) + m[2], intro, flags=re.MULTILINE)
    library.write_text(intro + '\n\n' + MARKER + '\n\n' + '\n\n'.join(sections) + '\n', encoding='utf-8')


if __name__ == '__main__':
    if '--' in sys.argv: worker(Path(sys.argv[sys.argv.index('--') + 1]))
    else: main(sys.argv[1:])
